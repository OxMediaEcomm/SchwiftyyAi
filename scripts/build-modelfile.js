#!/usr/bin/env node
// Generates ollama/Modelfile from schwiftyy/identity.md so the chat-only
// local Schwiftyy and the Claude Code one share a single personality.
// Run: npm run build:modelfile   (CI fails if the committed file is stale)

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BASE_MODEL = process.env.SCHWIFTYY_BASE_MODEL || 'llama3.1:8b';

// Sections that only make sense inside Claude Code (slash commands, tools).
const CLAUDE_CODE_ONLY = ['Per-Mode Voice Calibration'];

function build() {
  const identity = fs.readFileSync(path.join(ROOT, 'schwiftyy', 'identity.md'), 'utf8');
  const sections = identity.split(/^(?=## )/m).filter((s) => {
    const title = s.match(/^## (.+)$/m)?.[1]?.trim();
    return !CLAUDE_CODE_ONLY.includes(title);
  });
  const persona = sections
    .join('')
    .split('\n')
    .filter((line) => !line.includes('portal.js')) // "get schwifty" needs Bash
    .join('\n')
    .trim();

  const local = `## Running locally

You are running as a local, offline model in Ollama, without Claude Code. You have no file access, no code execution and no memory between chats. If someone asks you to edit files, run commands, or remember them next time, say plainly that this needs Schwiftyy inside Claude Code, then help as much as you can in chat (explain, review pasted code, write code for them to paste). Never pretend you did something you can't do. Be honest when a question is beyond what a small local model does well.`;

  if (persona.includes('"""')) throw new Error('identity.md contains """, which breaks the Modelfile');

  return `# GENERATED by scripts/build-modelfile.js from schwiftyy/identity.md — do not edit by hand.
# Swap the base model: SCHWIFTYY_BASE_MODEL=qwen2.5:14b npm run build:modelfile
# Then: ollama create schwiftyy -f ollama/Modelfile && ollama run schwiftyy

FROM ${BASE_MODEL}

PARAMETER temperature 0.8
PARAMETER num_ctx 8192

SYSTEM """
${persona}

${local}
"""
`;
}

module.exports = { build };

if (require.main === module) {
  const out = path.join(ROOT, 'ollama', 'Modelfile');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, build());
  console.log(`wrote ${path.relative(ROOT, out)} (FROM ${BASE_MODEL})`);
}
